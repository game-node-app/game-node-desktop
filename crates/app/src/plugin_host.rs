#[cfg(all(test, target_os = "linux"))]
mod inventory_tests {
    use super::*;

    #[test]
    fn inventory_derives_from_descriptors_for_the_current_platform() {
        let platform = Platform::current().unwrap();
        let visible: Vec<&PluginDescriptor> = descriptors()
            .iter()
            .filter(|descriptor| descriptor.supports(platform))
            .collect();
        let first = visible.first().expect("a descriptor for this platform");
        let directory = tempfile::tempdir().unwrap();
        for descriptor in descriptors() {
            std::fs::write(
                directory.path().join(descriptor.executable_name()),
                b"fixture",
            )
            .unwrap();
        }
        let reported = inventory_at(Some(directory.path()), |id| {
            if id == first.provider_id {
                ("failed", false)
            } else {
                ("installed", true)
            }
        });
        assert_eq!(reported.len(), visible.len());
        for descriptor in &visible {
            let info = reported
                .iter()
                .find(|info| info.provider_id == descriptor.provider_id)
                .unwrap();
            assert_eq!(info.name, descriptor.name);
            assert_eq!(info.capabilities, descriptor.capabilities);
            assert_eq!(info.native_access, descriptor.native_access);
            if descriptor.provider_id == first.provider_id {
                assert_eq!(
                    (info.status.as_str(), info.session.as_str()),
                    ("failed", "stopped")
                );
            } else {
                assert_eq!(
                    (info.status.as_str(), info.session.as_str()),
                    ("installed", "active")
                );
            }
        }
        for descriptor in descriptors()
            .iter()
            .filter(|descriptor| !descriptor.supports(platform))
        {
            assert!(
                reported
                    .iter()
                    .all(|info| info.provider_id != descriptor.provider_id)
            );
        }

        let empty = tempfile::tempdir().unwrap();
        let missing = inventory_at(Some(empty.path()), |_| ("installed", true));
        assert_eq!(missing.len(), visible.len());
        assert!(missing.iter().all(|info| info.status == "missing"));
        drop(directory);
    }
}
