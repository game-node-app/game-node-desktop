/// Read-only inventory of the bundled provider executables.
#[derive(Clone, Debug, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct PluginInfo {
    pub provider_id: String,
    pub plugin_id: String,
    pub name: String,
    pub source: String,
    pub status: String,
    pub capabilities: Vec<String>,
    pub session: String,
    pub native_access: Vec<String>,
}

/// Resolving the current executable and checking sibling files touches disk;
/// callers should run this on a blocking worker.
pub fn inventory(health: impl Fn(&str) -> (&'static str, bool)) -> Vec<PluginInfo> {
    let executable_dir = std::env::current_exe()
        .ok()
        .and_then(|path| path.parent().map(std::path::Path::to_path_buf));
    inventory_at(executable_dir.as_deref(), health)
}

fn inventory_at(
    executable_dir: Option<&std::path::Path>,
    health: impl Fn(&str) -> (&'static str, bool),
) -> Vec<PluginInfo> {
    let Some(platform) = Platform::current() else {
        return Vec::new();
    };
    descriptors()
        .iter()
        .filter(|plugin| plugin.supports(platform))
        .map(|plugin| {
            let installed =
                executable_dir.is_some_and(|dir| dir.join(plugin.executable_name()).is_file());
            let (runtime_status, connected) = health(&plugin.provider_id);
            PluginInfo {
                provider_id: plugin.provider_id.clone(),
                plugin_id: plugin.plugin_id.clone(),
                name: plugin.name.clone(),
                source: "official".to_owned(),
                status: if !installed {
                    "missing"
                } else {
                    runtime_status
                }
                .to_owned(),
                capabilities: plugin.capabilities.clone(),
                session: if connected { "active" } else { "stopped" }.into(),
                native_access: plugin.native_access.clone(),
            }
        })
        .collect()
}

/// One trusted, bundled plugin descriptor, parsed from `plugins/*.toml`.
///
/// Host code reads every provider fact from this data: inventory, backends, login policy,
/// credentials, native access and legacy profile cleanup. Adding a store must not add a Rust
/// branch here.
#[derive(Clone, Debug)]
pub(crate) struct PluginDescriptor {
    pub provider_id: String,
    pub plugin_id: String,
    pub name: String,
    pub platforms: Vec<Platform>,
    pub capabilities: Vec<String>,
    pub executable: String,
    /// Provider id of the embedded `providers/<id>.toml` manifest.
    pub provider_manifest: String,
    /// The embedded manifest text consumed by the scoped provider services.
    pub manifest_toml: String,
    pub login_policy: Option<LoginPolicy>,
    /// Existing physical credential names, when the provider must keep them.
    pub credential_alias: Option<CredentialAlias>,
    pub native_access: Vec<String>,
    pub legacy_login_profiles: Vec<String>,
}

impl PluginDescriptor {
    pub fn executable_name(&self) -> String {
        if cfg!(windows) {
            format!("{}.exe", self.executable)
        } else {
            self.executable.clone()
        }
    }

    pub fn supports(&self, platform: Platform) -> bool {
        self.platforms.contains(&platform)
    }

    pub fn has(&self, capability: &str) -> bool {
        self.capabilities
            .iter()
            .any(|granted| granted == capability)
    }

    pub fn approved_login(&self) -> Result<Option<LoginPolicy>, Status> {
        if let Some(policy) = &self.login_policy {
            policy
                .validate()
                .map_err(|_| Status::failed_precondition("invalid login policy"))?;
        }
        Ok(self.login_policy.clone())
    }

    /// The physical credential slot for this provider, applying its descriptor alias.
    pub fn credential_slot(&self) -> CredentialSlot {
        CredentialSlot::provider(&self.provider_id, self.credential_alias.clone())
    }

    /// Whether this descriptor grants any logical secret operation.
    pub fn uses_secrets(&self) -> bool {
        self.has(capability::SECRET_READ)
            || self.has(capability::SECRET_WRITE)
            || self.has(capability::SECRET_DELETE)
    }
}

#[derive(serde::Deserialize)]
#[serde(deny_unknown_fields)]
struct DescriptorFile {
    provider_id: String,
    plugin_id: String,
    name: String,
    platforms: Vec<Platform>,
    capabilities: Vec<String>,
    executable: String,
    provider_manifest: String,
    #[serde(default)]
    login_policy: Option<String>,
    #[serde(default)]
    credential_alias: Option<CredentialAlias>,
    #[serde(default)]
    native_access: Vec<String>,
    #[serde(default)]
    legacy_login_profiles: Vec<String>,
}

#[derive(Debug)]
struct DescriptorDiagnostic {
    file: String,
    problem: String,
}

#[derive(Default)]
struct LoadedDescriptors {
    descriptors: Vec<PluginDescriptor>,
    diagnostics: Vec<DescriptorDiagnostic>,
}

/// Parses and validates every descriptor. An invalid file is skipped with a diagnostic; the
/// remaining descriptors still load.
fn load_descriptors(
    manifests: &[(&str, &str)],
    sources: &[(&str, &str)],
    policies: &[(&str, &str)],
) -> LoadedDescriptors {
    let mut ordered: Vec<&(&str, &str)> = sources.iter().collect();
    ordered.sort_by_key(|(file, _)| *file);

    let mut loaded = LoadedDescriptors::default();
    let mut provider_ids = BTreeSet::new();
    let mut keyring_slots: BTreeMap<String, String> = BTreeMap::new();
    let mut file_slots: BTreeMap<String, String> = BTreeMap::new();
    for (file, source) in ordered {
        let descriptor = match parse_descriptor(source, manifests, policies) {
            Ok(descriptor) => descriptor,
            Err(problem) => {
                loaded.diagnostics.push(DescriptorDiagnostic {
                    file: (*file).to_owned(),
                    problem,
                });
                continue;
            }
        };
        if !provider_ids.insert(descriptor.provider_id.clone()) {
            loaded.diagnostics.push(DescriptorDiagnostic {
                file: (*file).to_owned(),
                problem: format!("duplicate provider id `{}`", descriptor.provider_id),
            });
            continue;
        }
        let slot = descriptor.credential_slot();
        let keyring_account = slot.keyring_account().to_owned();
        let private_file = match &slot {
            CredentialSlot::Provider { private_file, .. } => private_file.clone(),
            CredentialSlot::Session => unreachable!("descriptors use provider credential slots"),
        };
        if let Some(existing) = keyring_slots.get(&keyring_account) {
            loaded.diagnostics.push(DescriptorDiagnostic {
                file: (*file).to_owned(),
                problem: format!("credential slot collides with provider `{existing}`"),
            });
            continue;
        }
        if let Some(existing) = file_slots.get(&private_file) {
            loaded.diagnostics.push(DescriptorDiagnostic {
                file: (*file).to_owned(),
                problem: format!("credential slot collides with provider `{existing}`"),
            });
            continue;
        }
        keyring_slots.insert(keyring_account, descriptor.provider_id.clone());
        file_slots.insert(private_file, descriptor.provider_id.clone());
        loaded.descriptors.push(descriptor);
    }
    loaded
}

fn parse_descriptor(
    source: &str,
    manifests: &[(&str, &str)],
    policies: &[(&str, &str)],
) -> Result<PluginDescriptor, String> {
    let file: DescriptorFile = toml::from_str(source)
        .map_err(|error| format!("invalid descriptor: {}", error.message()))?;

    if !plain_provider_id(&file.provider_id) {
        return Err("provider id is not a plain lowercase id".to_owned());
    }
    if file.provider_manifest != file.provider_id {
        return Err("provider manifest does not name the provider id".to_owned());
    }
    let manifest_name = format!("{}.toml", file.provider_manifest);
    let manifest_text = manifests
        .iter()
        .find(|(name, _)| *name == manifest_name)
        .map(|(_, text)| *text)
        .ok_or_else(|| "provider manifest is not embedded".to_owned())?;
    let manifest: Manifest = toml::from_str(manifest_text)
        .map_err(|error| format!("invalid provider manifest: {}", error.message()))?;
    if manifest.id != file.provider_id {
        return Err("provider manifest id does not match the provider id".to_owned());
    }
    if !file
        .platforms
        .iter()
        .all(|platform| manifest.platforms.contains(platform))
    {
        return Err("descriptor platform is not declared by its provider manifest".to_owned());
    }

    let mut known = BTreeSet::new();
    for capability in &file.capabilities {
        if !capability::ALL.contains(&capability.as_str()) {
            return Err(format!("unknown capability `{capability}`"));
        }
        if !known.insert(capability.as_str()) {
            return Err(format!("duplicate capability `{capability}`"));
        }
    }
    let has = |wanted: &str| file.capabilities.iter().any(|granted| granted == wanted);

    let login_policy = file
        .login_policy
        .as_ref()
        .map(|path| {
            let path = path.replace('\\', "/");
            let text = policies
                .iter()
                .find(|(name, _)| *name == path)
                .map(|(_, text)| *text)
                .ok_or_else(|| "login policy is not embedded".to_owned())?;
            let policy: LoginPolicy = toml::from_str(text)
                .map_err(|error| format!("invalid login policy: {}", error.message()))?;
            policy
                .validate()
                .map_err(|_| "invalid login policy".to_owned())?;
            Ok::<LoginPolicy, String>(policy)
        })
        .transpose()?;
    if login_policy.is_some() != has(capability::LOGIN) {
        return Err("login policy presence does not match the auth.webview grant".to_owned());
    }
    if has(capability::COOKIES)
        && login_policy
            .as_ref()
            .is_none_or(|policy| policy.cookie_names.is_empty())
    {
        return Err("cookie grant requires a login policy with cookie names".to_owned());
    }
    if let Some(alias) = &file.credential_alias
        && !alias.is_valid()
    {
        return Err(
            "credential alias must be a plain provider name, not the GameNode session slot"
                .to_owned(),
        );
    }
    if file
        .legacy_login_profiles
        .iter()
        .any(|profile| !plain_name(profile) || profile == gamenode_platform::paths::LOGIN_DIR)
    {
        return Err("legacy login profile is not a plain profile name".to_owned());
    }

    Ok(PluginDescriptor {
        provider_id: file.provider_id,
        plugin_id: file.plugin_id,
        name: file.name,
        platforms: file.platforms,
        capabilities: file.capabilities,
        executable: file.executable,
        provider_manifest: file.provider_manifest,
        manifest_toml: manifest_text.to_owned(),
        login_policy,
        credential_alias: file.credential_alias,
        native_access: file.native_access,
        legacy_login_profiles: file.legacy_login_profiles,
    })
}

fn plain_provider_id(provider_id: &str) -> bool {
    !provider_id.is_empty()
        && provider_id.bytes().all(|byte| {
            byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'-' || byte == b'_'
        })
}

fn plain_name(name: &str) -> bool {
    !name.is_empty()
        && name.len() <= 128
        && name != "."
        && name != ".."
        && name
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'.' | b'-' | b'_'))
}

/// Loads the trusted descriptors once. Invalid descriptors are reported and skipped.
pub(crate) fn descriptors() -> &'static [PluginDescriptor] {
    static DESCRIPTORS: OnceLock<Vec<PluginDescriptor>> = OnceLock::new();
    DESCRIPTORS.get_or_init(|| {
        let loaded = load_descriptors(
            crate::providers::BUNDLED_MANIFESTS,
            BUNDLED_PLUGIN_DESCRIPTORS,
            BUNDLED_LOGIN_POLICIES,
        );
        for diagnostic in &loaded.diagnostics {
            tracing::warn!(
                descriptor = %diagnostic.file,
                problem = %diagnostic.problem,
                "invalid bundled plugin descriptor"
            );
        }
        loaded.descriptors
    })
}

pub fn legacy_login_profiles() -> Vec<String> {
    descriptors()
        .iter()
        .flat_map(|plugin| plugin.legacy_login_profiles.iter().cloned())
        .collect()
}

pub(crate) fn descriptor_for_provider(provider_id: &str) -> Option<&'static PluginDescriptor> {
    descriptors()
        .iter()
        .find(|plugin| plugin.provider_id == provider_id)
}

pub fn backends(platform: Platform) -> Vec<gamenode_core::provider::PluginBackend> {
    descriptors()
        .iter()
        .filter(|plugin| plugin.supports(platform))
        .map(|plugin| gamenode_core::provider::PluginBackend {
            plugin_id: plugin.plugin_id.clone(),
            provider_id: plugin.provider_id.clone(),
            discovery: plugin.has(capability::DISCOVERY),
            catalog: plugin.has(capability::CATALOG),
            counter: plugin.has(capability::COUNTER),
            actions: plugin.has(capability::ACTIONS),
            achievements: plugin.has(capability::ACHIEVEMENTS),
        })
        .collect()
}

