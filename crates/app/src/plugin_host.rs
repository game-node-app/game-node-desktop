/// One component of an installed bundle as the inventory reports it.
///
/// A bundle is one entry in the inventory, but each component keeps its own identity, status and
/// lifecycle. This is the display projection of a component; it carries no grants and never
/// replaces the component's own [`PluginInfo`] facts in the registry.
#[derive(Clone, Debug, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct PluginBundleComponent {
    pub plugin_id: String,
    /// `provider` or `extension`.
    pub plugin_kind: String,
    pub name: String,
    pub version: String,
    /// Component status: `installed`, `unavailable`, `incompatible`, `missing` or `failed`.
    pub status: String,
    pub session: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub enabled: Option<bool>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub runtime_available: Option<bool>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub publisher_fingerprint: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub compatibility_details: Option<managed_packages::PackageCompatibilityReview>,
    #[serde(skip_serializing_if = "Vec::is_empty")]
    pub native_access: Vec<String>,
}

/// Read-only inventory of official provider executables and installed community packages.
#[derive(Clone, Debug, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct PluginInfo {
    pub provider_id: String,
    pub plugin_id: String,
    /// Package execution kind from the verified manifest; bundled plugins are providers and an
    /// aggregated bundle entry is `bundle`.
    pub plugin_kind: String,
    pub name: String,
    /// The version declared by the trusted descriptor, or the build's package version.
    pub version: String,
    pub source: String,
    pub status: String,
    pub capabilities: Vec<String>,
    pub session: String,
    pub native_access: Vec<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub enabled: Option<bool>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub runtime_available: Option<bool>,
    /// The pinned publisher of a third-party plugin; `None` for the bundled ones. The settings
    /// use it, with `plugin_id`, to find what the user allowed this plugin to start. An aggregated
    /// bundle entry leaves it unset so bundle-wide actions never run as a single component.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub publisher_fingerprint: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub compatibility_details: Option<managed_packages::PackageCompatibilityReview>,
    /// The bundle this entry belongs to; absent for a standalone package or an official plugin.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub bundle_id: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub bundle_name: Option<String>,
    /// The bundle's distribution version, independent of each component's package version.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub bundle_version: Option<String>,
    /// The component kind when the entry is a single installed component of a bundle.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub bundle_component_kind: Option<String>,
    /// The bundle's pinned publisher fingerprint. Set only on the aggregated bundle entry, so the
    /// row can show the publisher without offering single-component management.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub bundle_publisher_fingerprint: Option<String>,
    /// Every component of the bundle and its current status, in bundle-manifest order.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub bundle_components: Option<Vec<PluginBundleComponent>>,
}

/// Resolving the current executable and checking sibling files touches disk;
/// callers should run this on a blocking worker.
pub fn inventory(health: impl Fn(&str) -> (&'static str, bool)) -> Vec<PluginInfo> {
    let executable_dir = std::env::current_exe()
        .ok()
        .and_then(|path| path.parent().map(std::path::Path::to_path_buf));
    inventory_at(executable_dir.as_deref(), health)
}

fn inventory_at(
    executable_dir: Option<&std::path::Path>,
    health: impl Fn(&str) -> (&'static str, bool),
) -> Vec<PluginInfo> {
    let Some(platform) = Platform::current() else {
        return Vec::new();
    };
    descriptors()
        .iter()
        .filter(|plugin| plugin.supports(platform))
        .map(|plugin| {
            let installed =
                executable_dir.is_some_and(|dir| dir.join(plugin.executable_name()).is_file());
            let (runtime_status, connected) = health(&plugin.provider_id);
            PluginInfo {
                provider_id: plugin.provider_id.clone(),
                plugin_id: plugin.plugin_id.clone(),
                plugin_kind: "provider".to_owned(),
                name: plugin.name.clone(),
                version: plugin.version.clone(),
                source: "official".to_owned(),
                status: if !installed {
                    "missing"
                } else {
                    runtime_status
                }
                .to_owned(),
                capabilities: plugin.capabilities.clone(),
                session: if connected { "active" } else { "stopped" }.into(),
                native_access: plugin.native_access.clone(),
                enabled: None,
                runtime_available: None,
                publisher_fingerprint: None,
                compatibility_details: None,
                bundle_id: None,
                bundle_name: None,
                bundle_version: None,
                bundle_component_kind: None,
                bundle_publisher_fingerprint: None,
                bundle_components: None,
            }
        })
        .collect()
}

/// One trusted, bundled plugin descriptor, parsed from `plugins/*.toml`.
///
/// Host code reads every provider fact from this data: inventory, backends, login policy,
/// credentials, native access and legacy profile cleanup. Adding a store must not add a Rust
/// branch here.
#[derive(Clone, Debug)]
pub(crate) struct PluginDescriptor {
    pub provider_id: String,
    pub plugin_id: String,
    pub name: String,
    /// The trusted descriptor's version, or the build package version when it declares none.
    pub version: String,
    pub platforms: Vec<Platform>,
    pub capabilities: Vec<String>,
    pub executable: String,
    /// Provider id of the embedded `providers/<id>.toml` manifest.
    pub provider_manifest: String,
    /// The embedded manifest text consumed by the scoped provider services.
    pub manifest_toml: String,
    /// Whether the embedded provider manifest declares shared catalog access.
    pub shared_catalog: bool,
    pub login_policy: Option<LoginPolicy>,
    /// Existing physical credential names, when the provider must keep them.
    pub credential_alias: Option<CredentialAlias>,
    pub native_access: Vec<String>,
    pub legacy_login_profiles: Vec<String>,
    /// Image hosts this provider may download achievement icons from.
    pub achievement_icon_hosts: Vec<String>,
}

impl PluginDescriptor {
    pub fn executable_name(&self) -> String {
        if cfg!(windows) {
            format!("{}.exe", self.executable)
        } else {
            self.executable.clone()
        }
    }

    pub fn supports(&self, platform: Platform) -> bool {
        self.platforms.contains(&platform)
    }

    pub fn has(&self, capability: &str) -> bool {
        self.capabilities
            .iter()
            .any(|granted| granted == capability)
    }

    pub fn approved_login(&self) -> Result<Option<LoginPolicy>, Status> {
        if let Some(policy) = &self.login_policy {
            policy
                .validate()
                .map_err(|_| Status::failed_precondition("invalid login policy"))?;
        }
        Ok(self.login_policy.clone())
    }

    /// The physical credential slot for this provider, applying its descriptor alias.
    pub fn credential_slot(&self) -> CredentialSlot {
        CredentialSlot::provider(&self.provider_id, self.credential_alias.clone())
    }

    /// Whether this descriptor grants any logical secret operation.
    pub fn uses_secrets(&self) -> bool {
        self.has(capability::SECRET_READ)
            || self.has(capability::SECRET_WRITE)
            || self.has(capability::SECRET_DELETE)
    }
}

